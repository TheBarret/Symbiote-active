#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>
#include <lib/mem.h>
#include <core/version.h>
#include <core/services/random.h>
#include <core/panic.h>
#include <core/klog.h>

/* codebase: 0.2.0 */

/* Randomizer
 * Ring layout (see rnd_ring_byte / rnd_next):
 *   rnd_next() advances xorshift16, writes the result's low byte at
 *   ring[head], then increments head modulo RND_RING_SIZE.
 *
 *   Therefore ring[head] is always the *oldest* byte (the next to be
 *   overwritten), and the newest byte lives at (head - 1) mod RND_RING_SIZE.
 *
 *   A pure reader sees a sliding 256-byte window over the deterministic
 *   stream, indexed 0..255 with no wraparound surprise: slot i means
 *   "the byte that was written i steps ago relative to head", i.e. an
 *   absolute position in the stream, not a ring index. The mapping is:
 *
 *       absolute = stream_count - RND_RING_SIZE + slot   (if slot < filled)
 *       ring_index = absolute % RND_RING_SIZE
 *
 *   For simplicity and determinism, slot i maps to ring[i] directly; readers
 *   that care about "newest" should use (head - 1) mod RND_RING_SIZE, which
 *   this module exposes only via rnd_ring_byte's caller's responsibility.
 *   In practice, ISA reads at slot 0..255 see the last 256 generated bytes
 *   in the order they were written into the ring, oldest-first. */

static uint16_t g_state;
static uint8_t  g_ring[RND_RING_SIZE];
static uint32_t g_head;            /* next write index, 0..RND_RING_SIZE-1 */
static uint64_t g_count;           /* total bytes ever generated */

void rnd_init(uint16_t seed) {
    if (seed == 0) {
        seed = (uint16_t)255;
        klog_warning("rnd_init() seed parameter cannot be zero, using fallback...\n");
    }
    g_state = seed;
    memset(g_ring, 0, sizeof g_ring);
    g_head  = 0;
    g_count = 0;
    klog_serv("Randomizer: type=xorshift16, seed=0x%04x, ring=%u\n", seed, RND_RING_SIZE);
}

uint16_t rnd_next(void) {
    uint16_t x = g_state;
    x ^= (uint16_t)(x << 7);
    x ^= (uint16_t)(x >> 9);
    x ^= (uint16_t)(x << 8);
    g_state = x;

    g_ring[g_head] = (uint8_t)(x & 0xFFu);
    g_head = (g_head + 1u) % RND_RING_SIZE;
    g_count++;

    return x;
}

uint8_t rnd_ring_byte(uint32_t off) {
    if (off >= RND_RING_SIZE) return 0;
    return g_ring[off];
}
